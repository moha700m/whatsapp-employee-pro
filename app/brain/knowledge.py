def default_kb():
    return {"products": copy.deepcopy(PRODUCTS), "occasions": copy.deepcopy(OCCASIONS), "meanings": dict(FLOWER_MEANINGS),
            "care": list(CARE_TIPS), "cities": copy.deepcopy(CITIES), "faq": copy.deepcopy(DELIVERY_FAQ),
            "templates": copy.deepcopy(TEMPLATES), "upsell": copy.deepcopy(UPSELL), "shop": dict(DEFAULT_SHOP)}

def load_kb(repo=None):
    kb = default_kb()
    if repo is not None:
        raw = repo.get_setting("brain.kb", "")
        if raw:
            try:
                over = json.loads(raw)
                for k, v in over.items():
                    if k in kb and isinstance(v, type(kb[k])): kb[k] = v
            except ValueError: pass
    return kb

def save_kb(repo, kb):
    repo.set_setting("brain.kb", json.dumps(kb, ensure_ascii=False))

def upcoming_occasions(today=None, days=45, kb=None):
    today = today or date.today(); out = []
    for name, o in (kb or default_kb())["occasions"].items():
        if o.get("dates"):   # Hijri occasions: expected Gregorian dates (Umm al-Qura estimates, confirmed by the official announcement)
            nxt = next((date.fromisoformat(x) for x in sorted(o["dates"]) if date.fromisoformat(x) >= today), None)
            if not nxt: continue
        elif not o.get("date"): continue
        else:
            m, d = map(int, o["date"].split("-"))
            nxt = date(today.year, m, d)
            if nxt < today: nxt = date(today.year + 1, m, d)
        if (nxt - today).days <= days: out.append({"occasion": name, "date": nxt.isoformat(), "days": (nxt - today).days})
    return sorted(out, key=lambda x: x["days"])
